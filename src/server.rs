//! HTTP server exposing the published lock, signature, manifest, and UI.

use std::{
    io::{Read, Seek, SeekFrom},
    path::Path,
};

use axum::{
    http::{header, StatusCode},
    response::{IntoResponse, Response},
};

use crate::{
    config::Cfg,
    ui::{index_html, ui_json, UiState},
};

fn serve_file(dir: &Path, name: &str, content_type: &'static str) -> Response {
    let path = dir.join(name);
    match std::fs::read(&path) {
        Ok(bytes) => ([(header::CONTENT_TYPE, content_type)], bytes).into_response(),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            (StatusCode::NOT_FOUND, "not yet published\n").into_response()
        }
        Err(e) => {
            log::error!("reading {}: {e}", path.display());
            (StatusCode::INTERNAL_SERVER_ERROR, "error reading file\n").into_response()
        }
    }
}

const TAIL_BYTES: u64 = 32 * 1024;

fn serve_log_tail(dir: &Path, name: &str) -> Response {
    let result = (|| -> std::io::Result<String> {
        let mut file = std::fs::File::open(dir.join(name))?;
        let length = file.metadata()?.len();
        file.seek(SeekFrom::Start(length.saturating_sub(TAIL_BYTES)))?;
        let mut bytes = Vec::new();
        file.take(TAIL_BYTES).read_to_end(&mut bytes)?;
        Ok(String::from_utf8_lossy(&bytes).into_owned())
    })();
    match result {
        Ok(text) => (
            [
                (header::CONTENT_TYPE, "text/plain; charset=utf-8"),
                (header::CACHE_CONTROL, "no-store"),
            ],
            text,
        )
            .into_response(),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            (StatusCode::NOT_FOUND, "log unavailable\n").into_response()
        }
        Err(e) => {
            log::error!("reading log tail: {e}");
            (StatusCode::INTERNAL_SERVER_ERROR, "error reading log\n").into_response()
        }
    }
}

/// Log names are generated by us, but the route accepts user input. Allow
/// only a single, simple `*.log` filename beneath `serve_dir/logs`.
fn valid_log_name(name: &str) -> bool {
    !name.is_empty()
        && name.ends_with(".log")
        && !name.starts_with('.')
        && !name.contains("..")
        && name
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
}

pub fn build_router(cfg: &Cfg, ui: UiState) -> axum::Router {
    let cfg = std::sync::Arc::new(cfg.clone());
    let serve_dir = std::sync::Arc::new(cfg.serve_dir.clone());
    let file_route = |path: &'static str, content_type: &'static str| {
        let dir = serve_dir.clone();
        axum::routing::get(move || {
            let dir = dir.clone();
            async move { serve_file(&dir, path, content_type) }
        })
    };
    axum::Router::new()
        .route(
            "/",
            axum::routing::get(|| async {
                (
                    [(header::CONTENT_TYPE, "text/html; charset=utf-8")],
                    index_html(),
                )
            }),
        )
        .route(
            "/live-log",
            axum::routing::get(|| async {
                (
                    [(header::CONTENT_TYPE, "text/html; charset=utf-8")],
                    include_str!("ui/live-log.html"),
                )
            }),
        )
        .route(
            "/ui.json",
            axum::routing::get({
                let cfg = cfg.clone();
                move || {
                    let cfg = cfg.clone();
                    async move {
                        let body = ui_json(&ui, &cfg);
                        (
                            [(header::CONTENT_TYPE, "application/json")],
                            body.to_string(),
                        )
                            .into_response()
                    }
                }
            }),
        )
        .route("/healthz", axum::routing::get(|| async { "ok" }))
        .route("/flake.lock", file_route("flake.lock", "application/json"))
        .route(
            "/flake.lock.minisig",
            file_route("flake.lock.minisig", "text/plain; charset=utf-8"),
        )
        .route(
            "/manifest.json",
            file_route("manifest.json", "application/json"),
        )
        .route(
            "/log-tail/{host}",
            axum::routing::get({
                let dir = serve_dir.clone();
                move |path: axum::extract::Path<String>| {
                    let dir = dir.clone();
                    async move {
                        if !valid_log_name(&path.0) {
                            return (StatusCode::BAD_REQUEST, "bad log name\n").into_response();
                        }
                        serve_log_tail(&dir.join("logs"), &path.0)
                    }
                }
            }),
        )
        .route(
            "/logs/{host}",
            axum::routing::get({
                let dir = serve_dir.clone();
                move |path: axum::extract::Path<String>| {
                    let dir = dir.clone();
                    async move {
                        let host = path.0;
                        if !valid_log_name(&host) {
                            return (StatusCode::BAD_REQUEST, "bad log name\n").into_response();
                        }
                        serve_file(&dir.join("logs"), &host, "text/plain; charset=utf-8")
                    }
                }
            }),
        )
        .layer(tower_http::trace::TraceLayer::new_for_http())
}

#[cfg(test)]
mod tests {
    use axum::{
        body::Body,
        http::{Request, StatusCode},
    };
    use http_body_util::BodyExt;
    use tower::ServiceExt;

    use super::*;
    use crate::testing::{test_cfg, TempDir};

    fn request(uri: &str) -> Request<Body> {
        Request::builder().uri(uri).body(Body::empty()).unwrap()
    }

    async fn body_string(response: Response) -> String {
        let bytes = response.into_body().collect().await.unwrap().to_bytes();
        String::from_utf8(bytes.to_vec()).unwrap()
    }

    #[test]
    fn log_names_are_restricted_to_simple_log_files() {
        for valid in ["eris.log", "host-1.log", "host_2.log", "A.B9.log"] {
            assert!(valid_log_name(valid), "{valid} should be valid");
        }
        for invalid in [
            "",
            "..",
            "../eris.log",
            "logs/eris.log",
            "logs\\eris.log",
            ".log",
            ".hidden.log",
            "eris..log",
            "eris.log.tmp",
            "eris.txt",
            "eris log",
            "eris%2flog",
        ] {
            assert!(!valid_log_name(invalid), "{invalid} should be invalid");
        }
    }

    #[tokio::test]
    async fn serves_published_files_with_content_types() {
        let dir = TempDir::new("server-files");
        std::fs::write(dir.join("flake.lock"), br#"{"nodes":{}}"#).unwrap();
        std::fs::write(dir.join("manifest.json"), br#"{"status":"ok"}"#).unwrap();
        std::fs::write(dir.join("flake.lock.minisig"), b"signature\n").unwrap();

        let app = build_router(&test_cfg(&dir), UiState::new(&dir));

        let response = app.clone().oneshot(request("/flake.lock")).await.unwrap();
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(
            response.headers().get(header::CONTENT_TYPE).unwrap(),
            "application/json"
        );
        assert_eq!(body_string(response).await, r#"{"nodes":{}}"#);

        let response = app
            .clone()
            .oneshot(request("/manifest.json"))
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(body_string(response).await, r#"{"status":"ok"}"#);

        let response = app
            .clone()
            .oneshot(request("/flake.lock.minisig"))
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(body_string(response).await, "signature\n");
    }

    #[tokio::test]
    async fn serves_only_valid_log_filenames() {
        let dir = TempDir::new("server-logs");
        std::fs::create_dir_all(dir.join("logs")).unwrap();
        std::fs::write(dir.join("logs/eris.log"), b"build output\n").unwrap();

        let app = build_router(&test_cfg(&dir), UiState::new(&dir));

        let response = app
            .clone()
            .oneshot(request("/logs/eris.log"))
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(
            response.headers().get(header::CONTENT_TYPE).unwrap(),
            "text/plain; charset=utf-8"
        );
        assert_eq!(body_string(response).await, "build output\n");

        let response = app
            .clone()
            .oneshot(request("/logs/eris.txt"))
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::BAD_REQUEST);
    }

    #[tokio::test]
    async fn serves_live_log_page() {
        let dir = TempDir::new("server-live-log-page");
        let app = build_router(&test_cfg(&dir), UiState::new(&dir));
        let response = app.oneshot(request("/live-log")).await.unwrap();
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(
            response.headers()[header::CONTENT_TYPE],
            "text/html; charset=utf-8"
        );
        assert!(body_string(response).await.contains("Live build log"));
    }

    #[tokio::test]
    async fn tail_is_bounded_and_validates_names() {
        let dir = TempDir::new("server-tail");
        std::fs::create_dir_all(dir.join("logs")).unwrap();
        let mut bytes = vec![b'x'; TAIL_BYTES as usize + 100];
        bytes.extend_from_slice(b"end\n");
        std::fs::write(dir.join("logs/eris.log"), bytes).unwrap();
        let app = build_router(&test_cfg(&dir), UiState::new(&dir));
        let response = app
            .clone()
            .oneshot(request("/log-tail/eris.log"))
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(response.headers()[header::CACHE_CONTROL], "no-store");
        let body = body_string(response).await;
        assert_eq!(body.len(), TAIL_BYTES as usize);
        assert!(body.ends_with("end\n"));
        let response = app
            .clone()
            .oneshot(request("/log-tail/eris.txt"))
            .await
            .unwrap();
        assert_eq!(response.status(), StatusCode::BAD_REQUEST);
        let response = app.oneshot(request("/log-tail/missing.log")).await.unwrap();
        assert_eq!(response.status(), StatusCode::NOT_FOUND);
    }

    #[tokio::test]
    async fn missing_files_and_health_endpoint() {
        let dir = TempDir::new("server-missing");
        let app = build_router(&test_cfg(&dir), UiState::new(&dir));

        let response = app.clone().oneshot(request("/flake.lock")).await.unwrap();
        assert_eq!(response.status(), StatusCode::NOT_FOUND);

        let response = app.oneshot(request("/healthz")).await.unwrap();
        assert_eq!(response.status(), StatusCode::OK);
        assert_eq!(body_string(response).await, "ok");
    }
}
